"""EDITH-X Multi-Layer Enterprise Simulation Runner.

Simulates the ApexPay Technologies enterprise production workload across all 7 layers:
  Level 1: Qdrant Vector Knowledge Hybrid Ingestion & Retrieval
  Level 2: Context Information-Density Compression
  Level 3: Zero-Trust PCI-DSS PII & Shannon Entropy Secret Redaction
  Level 4: Calibrated Pareto Cost-Complexity Routing
  Level 5: Dual L0 Cache Engine (Exact + N-gram Semantic Hit)
  Level 6: Resilient Fallback Waterfall (Zero 500 Downtime)
  Level 7: Audited Financial Ledger & Prometheus Export
"""
import asyncio
import os
import sys
import time
from unittest.mock import AsyncMock, patch

from rich.console import Console
from rich.panel import Panel
from rich.table import Table

from edith_x.core.container import container
from edith_x.core.interfaces import Document, Context, IntentResult, PolicyDecision, ModelSelection
from edith_x.modules.policy.firewall import PIIFirewall

console = Console(force_terminal=True, legacy_windows=False)


async def run_simulation():
    console.print(Panel.fit(
        "[bold cyan]EDITH-X ENTERPRISE MULTI-LAYER USER TESTING SIMULATION[/bold cyan]\n"
        "[dim]Target Organization: ApexPay Technologies (Global Fintech & Payment Gateway)[/dim]",
        border_style="cyan"
    ))

    # ──────────────────────────────────────────────────────────────────────────
    # LEVEL 1: QDRANT HYBRID KNOWLEDGE INGESTION & RETRIEVAL
    # ──────────────────────────────────────────────────────────────────────────
    console.print("\n[bold yellow]>> LEVEL 1: Qdrant Hybrid Knowledge Ingestion & Retrieval[/bold yellow]")
    knowledge = container.knowledge()
    doc = Document(
        id="apexpay_sec_42",
        content=(
            "ApexPay Security Standard 4.2: All customer cardholder data at rest "
            "must be encrypted using AES-256-GCM. Secret keys must be rotated every 90 days. "
            "Any transmission across public networks requires TLS 1.3 with forward secrecy."
        ),
        source="apexpay_security_policy_v4.2.pdf",
        metadata={"classification": "confidential", "audit": "PCI-DSS-Level-1"},
    )
    t0 = time.perf_counter()
    await knowledge.index(doc, source="apexpay_security_policy_v4.2.pdf")
    t_index = (time.perf_counter() - t0) * 1000

    q = "What encryption standard is mandatory for customer cardholder data at rest?"
    t0 = time.perf_counter()
    chunks = await knowledge.retrieve(q, top_k=2)
    t_retrieve = (time.perf_counter() - t0) * 1000

    table1 = Table(title="Level 1: Hybrid Vector + Lexical Search Results", border_style="dim")
    table1.add_column("Source", style="cyan")
    table1.add_column("Hybrid Score", style="green")
    table1.add_column("Passage Content", style="white")
    for c in chunks:
        table1.add_row(c.source, f"{c.score:.4f}", c.content[:80] + "...")
    console.print(table1)
    console.print(f"[green][OK] Ingestion Latency: {t_index:.2f}ms | Retrieval Latency: {t_retrieve:.2f}ms[/green]")

    # ──────────────────────────────────────────────────────────────────────────
    # LEVEL 2: CONTEXT INFORMATION-DENSITY COMPRESSION
    # ──────────────────────────────────────────────────────────────────────────
    console.print("\n[bold yellow]>> LEVEL 2: Context Information-Density Compression[/bold yellow]")
    opt = container.optimization()
    verbose_policy = (
        "CONFIDENTIAL APEXPAY INTERNAL DOCUMENT. DO NOT DISTRIBUTE OUTSIDE AUTHORIZED CHANNELS. "
        "PLEASE NOTE THAT THE FOLLOWING MEMORANDUM CONTAINS CRITICAL OPERATIONAL INSTRUCTIONS. "
        "For dispute resolution on Regulation E transactions, refunds must be processed "
        "within 10 business days of notification. "
        "THIS MEMO HAS BEEN AUTOMATICALLY GENERATED BY THE SETTLEMENT AUDIT PIPELINE. "
        "IF YOU ARE NOT THE INTENDED RECIPIENT PLEASE DELETE THIS IMMEDIATE COMMUNICATION. "
        "Merchant chargebacks exceeding 1.5 percent ratio will incur a penalty surcharge of 250 dollars."
    )
    t0 = time.perf_counter()
    compressed = await opt.compress_prompt(verbose_policy, budget=30)
    t_compress = (time.perf_counter() - t0) * 1000

    reduction = (1.0 - (compressed.compressed_tokens / max(compressed.original_tokens, 1))) * 100
    console.print(f"Original Tokens: [bold]{compressed.original_tokens}[/bold] -> Compressed Tokens: [bold green]{compressed.compressed_tokens}[/bold green] ([bold green]-{reduction:.1f}% reduction[/bold green]) in {t_compress:.2f}ms")
    console.print(f"Retained High-Information Text: [italic]\"{compressed.compressed_text}\"[/italic]")

    # ──────────────────────────────────────────────────────────────────────────
    # LEVEL 3: ZERO-TRUST PCI-DSS PII & SECRET REDACTION FIREWALL
    # ──────────────────────────────────────────────────────────────────────────
    console.print("\n[bold yellow]>> LEVEL 3: Zero-Trust PCI-DSS PII & Shannon Entropy Secret Redaction[/bold yellow]")
    firewall = PIIFirewall()
    sensitive_payload = (
        "Customer Jane Doe dispute: Card Number 4532-0123-4567-8910, SSN 123-45-6789, "
        "Stripe Live Token: sk-live-7d8f9a0b1c2d3e4f5a6b7c8d9e0f1234, Email: jane@apexpay.internal"
    )
    t0 = time.perf_counter()
    sanitized, detected, types = firewall.redact(sensitive_payload)
    t_firewall = (time.perf_counter() - t0) * 1000

    table3 = Table(title="Level 3: Detected & Redacted Sensitive Entities", border_style="dim")
    table3.add_column("Detected Entity Types", style="red")
    table3.add_column("Air-Gapped Status", style="yellow")
    for t in types:
        table3.add_row(t.upper(), "ENFORCED LOCAL-ONLY")
    console.print(table3)
    console.print(f"[bold green]Sanitized Output:[/bold green] {sanitized}")
    console.print(f"[bold red]Policy Enforcement: AIR-GAPPED LOCAL ROUTING FORCED (Cloud API transfer blocked)[/bold red] in {t_firewall:.2f}ms")

    # ──────────────────────────────────────────────────────────────────────────
    # LEVEL 4: PARETO COST-COMPLEXITY MODEL ROUTING
    # ──────────────────────────────────────────────────────────────────────────
    console.print("\n[bold yellow]>> LEVEL 4: Calibrated Pareto Cost-Complexity Routing[/bold yellow]")
    router = container.router()
    
    # Query 1: Simple
    q_simple = Context(query="Convert this user list to JSON: ['Alice', 'Bob']")
    sel_simple = await router.route(q_simple, PolicyDecision(allowed_models=[]), IntentResult(type="task", complexity=0.1, risk=0.0, confidence=0.9))
    
    # Query 2: Complex
    q_complex = Context(query="Design a Byzantine-fault-tolerant consensus mechanism with multi-phase lock commit for settlement ledgers.")
    sel_complex = await router.route(q_complex, PolicyDecision(allowed_models=[]), IntentResult(type="coding", complexity=0.9, risk=0.1, confidence=0.95))

    table4 = Table(title="Level 4: Pareto Model Routing Decisions", border_style="dim")
    table4.add_column("Query Type", style="cyan")
    table4.add_column("Resolved Tier", style="bold")
    table4.add_column("Model Assigned", style="green")
    table4.add_column("Estimated Cost", style="white")
    table4.add_row("Simple Formatting", sel_simple.layer, sel_simple.model, f"${sel_simple.estimated_cost_usd:.5f}")
    table4.add_row("Distributed Architecture", sel_complex.layer, sel_complex.model, f"${sel_complex.estimated_cost_usd:.5f}")
    console.print(table4)

    # ──────────────────────────────────────────────────────────────────────────
    # LEVEL 5: HIGH-VOLUME L0 SEMANTIC CACHE TIER
    # ──────────────────────────────────────────────────────────────────────────
    console.print("\n[bold yellow]>> LEVEL 5: Dual L0 Cache Engine Performance[/bold yellow]")
    cache = container.optimization()
    q_cache = "What is the dispute chargeback window under Regulation E?"
    
    # Store initial response
    await cache.store_cache(q_cache, "Regulation E permits 60 days to report disputed charges.")
    
    # Check exact & semantic hit
    t0 = time.perf_counter()
    hit1 = await cache.check_cache(q_cache)
    t_hit1 = (time.perf_counter() - t0) * 1000

    q_rephrased = "Under Regulation E what is the timeframe allowed to dispute unauthorized debit card charges?"
    t0 = time.perf_counter()
    hit2 = await cache.check_cache(q_rephrased)
    t_hit2 = (time.perf_counter() - t0) * 1000

    console.print(f"Exact Hash Query Latency: [bold green]{t_hit1:.3f}ms[/bold green] | Cost: [bold green]$0.00000[/bold green] | Hit: {hit1.hit}")
    console.print(f"Semantic Cosine Query Latency: [bold green]{t_hit2:.3f}ms[/bold green] | Cost: [bold green]$0.00000[/bold green] | Hit: {hit2.hit if hit2 else False}")

    # ──────────────────────────────────────────────────────────────────────────
    # LEVEL 6: RESILIENT FALLBACK WATERFALL
    # ──────────────────────────────────────────────────────────────────────────
    console.print("\n[bold yellow]>> LEVEL 6: Resilient Multi-Provider Fallback Waterfall[/bold yellow]")
    exec_svc = container.execution()
    ctx_run = Context(query="Summarize daily settlement ledger.")
    sel_fail = ModelSelection(
        provider="nvidia",
        model="meta/llama-3.1-70b-instruct",
        reasoning="Primary cloud invocation",
        layer="L3_cloud",
    )

    success_resp = AsyncMock()
    success_resp.choices = [AsyncMock(message=AsyncMock(content="Settlement: 1,420 transactions successfully reconciled."))]
    success_resp.usage = AsyncMock(prompt_tokens=25, completion_tokens=10)

    with patch("litellm.acompletion", side_effect=[Exception("Cloud Provider Outage (HTTP 503)"), success_resp]):
        res = await exec_svc.execute(ctx_run, sel_fail)
        console.print(f"Primary Failure Intercepted: [bold red]Provider Outage[/bold red] -> Cascaded to Secondary Provider")
        console.print(f"Failover Status: [bold green]Active (Zero HTTP 500 downtime)[/bold green]")
        console.print(f"Response Received: [italic]\"{res.response}\"[/italic]")

    # ──────────────────────────────────────────────────────────────────────────
    # LEVEL 7: FINANCIAL AUDIT LEDGER & PROMETHEUS METRICS
    # ──────────────────────────────────────────────────────────────────────────
    console.print("\n[bold yellow]>> LEVEL 7: Audited Financial Ledger & Prometheus Export[/bold yellow]")
    obs = container.observability()
    cum_saved = obs.get_cumulative_savings()
    cum_cost = obs.get_cumulative_cost()
    prom_metrics = obs.generate_prometheus_metrics()

    console.print(Panel(
        f"[bold]Gross Cumulative Savings:[/bold] [bold green]${cum_saved:.5f}[/bold green]\n"
        f"[bold]Net Cloud Expenditure:[/bold] [cyan]${cum_cost:.5f}[/cyan]\n"
        f"[bold]Prometheus Metrics Sample:[/bold]\n[dim]{prom_metrics[:260]}...[/dim]",
        title="Level 7: Real-Time Observability Status",
        border_style="green"
    ))

    console.print("\n[bold green][OK] MULTI-LAYER USER TESTING SUCCESSFULLY COMPLETED ACROSS ALL 7 TIERS.[/bold green]\n")


if __name__ == "__main__":
    asyncio.run(run_simulation())
