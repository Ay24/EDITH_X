# LEVEL 3: ZERO-TRUST PII & HIGH-ENTROPY SECRET REDACTION FIREWALL
# ══════════════════════════════════════════════════════════════════════════════
@pytest.mark.asyncio
async def test_level3_pii_and_secret_redaction_firewall():
    """Verify Luhn-valid credit card, SSN, and high-entropy API key redaction and air-gapped enforcement."""
    sensitive_prompt = (
        "Process disputed transaction for user Jane Doe: "
        "Card Number: 4532-0123-4567-8910, SSN: 123-45-6789, "
        "Gateway Secret: export STRIPE_KEY=sk-live-7d8f9a0b1c2d3e4f5a6b7c8d9e0f1234 "
        "Email: jane.doe@apexpay.internal"
    )

    # 1. Direct scan endpoint test
    scan_resp = client.post(
        "/edith/v1/policy/scan",
        json={"text": sensitive_prompt},
        headers={"Authorization": "Bearer demo-key"},
    )
    assert scan_resp.status_code == 200
    scan_data = scan_resp.json()
    assert scan_data["has_pii_or_secrets"] is True
    assert scan_data["match_count"] >= 3
    redacted = scan_data["redacted"]
    assert "4532-0123-4567-8910" not in redacted
    assert "123-45-6789" not in redacted
    assert "sk-live-7d8f9a0b1c2d3e4f5a6b7c8d9e0f1234" not in redacted

    # 2. Runtime policy evaluation forces local air-gapped routing
    policy_svc = container.policy()
    intent_svc = container.intent()
    gateway_svc = container.gateway()
    auth = await gateway_svc.authenticate("demo-key")

    intent = await intent_svc.classify(sensitive_prompt, auth)
    decision = await policy_svc.evaluate(intent, auth, query=sensitive_prompt)
    assert decision.requires_local is True
    assert decision.pii_detected is True
    assert decision.data_residency == "local"


