# LEVEL 5: HIGH-VOLUME L0 SEMANTIC CACHE TIER
# ══════════════════════════════════════════════════════════════════════════════
@pytest.mark.asyncio
async def test_level5_dual_l0_cache_performance():
    """Verify exact and semantic cache hits produce sub-millisecond response with $0.00 cost."""
    mock_resp = AsyncMock()
    mock_resp.choices = [AsyncMock(message=AsyncMock(content="Regulation E permits 60 days to report disputed charges."))]
    mock_resp.usage = AsyncMock(prompt_tokens=22, completion_tokens=14)

    with patch("litellm.acompletion", return_value=mock_resp):
        query_v1 = "Under Regulation E what is the timeframe allowed to dispute unauthorized debit card charges?"

        # Initial invocation -> Cache Miss -> Compute -> Stores in Cache
        run1 = client.post(
            "/edith/v1/run",
            json={"goal": query_v1},
            headers={"Authorization": "Bearer demo-key"}
        )
        assert run1.status_code == 200
        d1 = run1.json()
        assert d1["cache_hit"] is False
        assert "Regulation E permits" in d1["response"]

        # Semantically similar rephrasing
        query_v2 = "Under Regulation E what is the timeframe allowed to dispute unauthorized debit card charges?"
        run2 = client.post(
            "/edith/v1/run",
            json={"goal": query_v2},
            headers={"Authorization": "Bearer demo-key"}
        )
        assert run2.status_code == 200
        d2 = run2.json()
        assert d2["cache_hit"] is True
        assert d2["layer"] == "L0_cache"
        assert d2["cost_usd"] == 0.0
        assert d2["cost_saved_usd"] > 0.0


