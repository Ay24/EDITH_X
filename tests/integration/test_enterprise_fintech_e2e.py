# ══════════════════════════════════════════════════════════════════════════════
# LEVEL 1: QDRANT HYBRID KNOWLEDGE INGESTION & RETRIEVAL
# ══════════════════════════════════════════════════════════════════════════════
@pytest.mark.asyncio
async def test_level1_qdrant_hybrid_knowledge():
    """Verify document chunking, vector indexing, and hybrid cosine+lexical search."""
    doc_payload = {
        "content": (
            "ApexPay Security Standard 4.2: All customer cardholder data at rest "
            "must be encrypted using AES-256-GCM. Secret keys must be rotated every 90 days. "
            "Any transmission across public networks requires TLS 1.3 with forward secrecy."
        ),
        "source": "apexpay_security_policy_v4.2.pdf",
        "metadata": {"classification": "confidential", "auditor": "PCI-DSS-QSA"},
    }

    # Ingest document
    resp = client.post("/edith/v1/documents", json=doc_payload, headers={"Authorization": "Bearer demo-key"})
    assert resp.status_code == 200
    doc_data = resp.json()
    assert doc_data["status"] == "indexed"
    assert "id" in doc_data

    # Query via hybrid retrieval
    q_resp = client.get(
        "/edith/v1/knowledge/query?q=What+encryption+standard+is+mandatory+for+cardholder+data+at+rest&top_k=2",
        headers={"Authorization": "Bearer demo-key"}
    )
    assert q_resp.status_code == 200
    q_data = q_resp.json()
    assert len(q_data["chunks"]) >= 1
    top_chunk = q_data["chunks"][0]
    assert "AES-256-GCM" in top_chunk["content"]
    assert top_chunk["score"] > 0.3
    assert top_chunk["source"] == "apexpay_security_policy_v4.2.pdf"


