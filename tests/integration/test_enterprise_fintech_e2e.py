# LEVEL 4: PARETO COST-COMPLEXITY MODEL ROUTING
# ══════════════════════════════════════════════════════════════════════════════
@pytest.mark.asyncio
async def test_level4_pareto_complexity_routing():
    """Verify low-complexity tasks route to L1/L2 and complex reasoning routes to L3."""
    router_svc = container.router()

    # Scenario A: Simple formatting / low complexity
    simple_ctx = Context(query="Format this list as JSON: ['USD', 'EUR', 'GBP']")
    simple_intent = IntentResult(type="task", complexity=0.1, risk=0.0, confidence=0.9)
    policy_clean = PolicyDecision(allowed_models=[])
    sel_simple = await router_svc.route(simple_ctx, policy_clean, simple_intent)
    assert sel_simple.layer in ("L1_local", "L2_compressed")

    # Scenario B: Complex architectural design & algorithm
    complex_ctx = Context(
        query=(
            "Architect a distributed settlement ledger using multi-phase commit, "
            "conflict-free replicated data types (CRDTs), and Byzantine fault tolerance. "
            "Include formal proof of safety invariants and high-throughput Python implementation."
        )
    )
    complex_intent = IntentResult(type="coding", complexity=0.9, risk=0.1, confidence=0.95)
    sel_complex = await router_svc.route(complex_ctx, policy_clean, complex_intent)
    assert sel_complex.layer == "L3_cloud"
    assert any(m in sel_complex.model.lower() for m in ("70b", "405b", "sonnet", "gpt-4o"))


