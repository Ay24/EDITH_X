# LEVEL 6: SELF-HEALING FALLBACK WATERFALL RESILIENCE
# ══════════════════════════════════════════════════════════════════════════════
@pytest.mark.asyncio
async def test_level6_fallback_waterfall_resilience():
    """Verify provider failures trigger waterfall cascade without HTTP 500 downtime."""
    from edith_x.core.interfaces import Context, ModelSelection

    exec_svc = container.execution()
    ctx = Context(query="Generate monthly reconciliation report summary.")
    sel = ModelSelection(
        provider="nvidia",
        model="meta/llama-3.1-70b-instruct",
        reasoning="Primary cloud invocation",
        layer="L3_cloud",
    )

    # Simulate primary failure and secondary success
    success_resp = AsyncMock()
    success_resp.choices = [AsyncMock(message=AsyncMock(content="Fallback settlement report: 1,420 transactions reconciled."))]
    success_resp.usage = AsyncMock(prompt_tokens=30, completion_tokens=15)

    with patch("litellm.acompletion", side_effect=[Exception("NVIDIA NIM 429 Rate Limit Exceeded"), success_resp]):
        res = await exec_svc.execute(ctx, sel)
        assert res.failover_active is True
        assert "1,420 transactions reconciled" in res.response
        assert res.tokens_output > 0


