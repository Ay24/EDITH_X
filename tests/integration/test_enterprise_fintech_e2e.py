# LEVEL 2: CONTEXT INFORMATION-DENSITY COMPRESSION
# ══════════════════════════════════════════════════════════════════════════════
@pytest.mark.asyncio
async def test_level2_context_compression():
    """Verify information-density compressor sheds boilerplate while preserving key semantics."""
    opt_svc = container.optimization()
    verbose_policy = (
        "CONFIDENTIAL APEXPAY INTERNAL DOCUMENT. DO NOT DISTRIBUTE OUTSIDE AUTHORIZED CHANNELS. "
        "PLEASE NOTE THAT THE FOLLOWING MEMORANDUM CONTAINS CRITICAL OPERATIONAL INSTRUCTIONS. "
        "For dispute resolution on Regulation E transactions, refunds must be processed "
        "within 10 business days of notification. "
        "THIS MEMO HAS BEEN AUTOMATICALLY GENERATED BY THE SETTLEMENT AUDIT PIPELINE. "
        "IF YOU ARE NOT THE INTENDED RECIPIENT PLEASE DELETE THIS IMMEDIATE COMMUNICATION. "
        "Merchant chargebacks exceeding 1.5 percent ratio will incur a penalty surcharge of 250 dollars."
    )

    compressed = await opt_svc.compress_prompt(verbose_policy, budget=30)
    assert compressed.compressed_tokens <= 32
    assert compressed.compression_ratio < 0.65
    assert "chargebacks" in compressed.compressed_text or "surcharge" in compressed.compressed_text or "Regulation E" in compressed.compressed_text


